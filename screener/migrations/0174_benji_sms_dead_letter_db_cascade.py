# MFB-2436: make the dead-letter table's conversation foreign key cascade in the
# DATABASE, as 0172 did for the other Benji SMS tables.
#
# A deletion request deletes the requester's conversations, and 0163 exists so that can
# be one raw DELETE. Without this migration that DELETE would fail on the first
# conversation with a dead-lettered job, since Django leaves the database constraint at
# NO ACTION and emulates the cascade in Python.
#
# Separate from 0173 for 0172's reason: CreateModel's foreign keys are added from the
# schema editor's deferred SQL after every operation in the migration has run, so a
# lookup inside 0173 would find no constraint to alter.
#
# The SQL is 0172's, copied rather than imported, so this migration does not depend on
# another migration module's private names.

from django.db import migrations

_TABLE = "screener_benjismsdeadletter"
_COLUMN = "conversation_id"
_REF_TABLE = "screener_assistantconversation"
_REF_COLUMN = "conversation_id"

# The constraint name is generated by Django and carries a hash, so it is looked up by
# the column it covers. INTO STRICT so a missing or ambiguous constraint raises instead
# of passing NULL to format(). DEFERRABLE INITIALLY DEFERRED is kept in both
# directions so ORM writes behave exactly as with Django's own foreign keys.
_LOOKUP_AND_REPLACE = """
DO $$
DECLARE
    fk_name text;
BEGIN
    SELECT c.conname INTO STRICT fk_name
    FROM pg_constraint c
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
    WHERE c.conrelid = '{table}'::regclass
      AND c.contype = 'f'
      AND a.attname = '{column}';

    EXECUTE format('ALTER TABLE {table} DROP CONSTRAINT %I', fk_name);
    EXECUTE format(
        'ALTER TABLE {table} ADD CONSTRAINT %I '
        'FOREIGN KEY ({column}) REFERENCES {ref_table}({ref_column}) '
        '{on_delete} DEFERRABLE INITIALLY DEFERRED',
        fk_name
    );
END $$;
"""


def _sql(on_delete: str) -> str:
    return _LOOKUP_AND_REPLACE.format(
        table=_TABLE,
        column=_COLUMN,
        ref_table=_REF_TABLE,
        ref_column=_REF_COLUMN,
        on_delete=on_delete,
    )


_ADD_DB_CASCADE = _sql("ON DELETE CASCADE")
_DROP_DB_CASCADE = _sql("")


class Migration(migrations.Migration):
    dependencies = [
        ("screener", "0173_benji_sms_dead_letter"),
    ]

    operations = [
        migrations.RunSQL(sql=_ADD_DB_CASCADE, reverse_sql=_DROP_DB_CASCADE),
    ]
