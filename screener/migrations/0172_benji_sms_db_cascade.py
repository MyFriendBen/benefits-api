# MFB-2435: make the Benji SMS tables' foreign keys cascade in the DATABASE, as 0163
# did for AssistantMessage -> AssistantConversation.
#
# Django emulates on_delete=CASCADE in Python and leaves the database constraint at NO
# ACTION. A deletion request ("remove my texts") deletes the requester's conversations,
# and 0163 exists so that can be one raw DELETE. Without this migration, that DELETE
# would fail on the first conversation with a binding, or the first message with a
# delivery row: the SMS tables would turn 0163's one-statement deletion back into a
# foreign-key violation.
#
# Separate from 0171 for 0163's reason: CreateModel's foreign keys are added from the
# schema editor's deferred SQL after every operation in the migration has run, so a
# lookup inside 0171 would find no constraint to alter.
#
# The WhiteLabel foreign key stays NO ACTION, matching on_delete=PROTECT.

from django.db import migrations

# (table, column, referenced table, referenced column). Children before parents does
# not matter here: each statement only rewrites one constraint.
_FOREIGN_KEYS = (
    (
        "screener_benjismsbinding",
        "conversation_id",
        "screener_assistantconversation",
        "conversation_id",
    ),
    ("screener_benjismsdelivery", "message_id", "screener_assistantmessage", "message_id"),
    ("screener_benjismsdelivery", "binding_id", "screener_benjismsbinding", "id"),
)

# The constraint name is generated by Django and carries a hash, so it is looked up by
# the column it covers. INTO STRICT so a missing or ambiguous constraint raises instead
# of passing NULL to format(). DEFERRABLE INITIALLY DEFERRED is kept in both
# directions so ORM writes behave exactly as with Django's own foreign keys.
_LOOKUP_AND_REPLACE = """
DO $$
DECLARE
    fk_name text;
BEGIN
    SELECT c.conname INTO STRICT fk_name
    FROM pg_constraint c
    JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = ANY (c.conkey)
    WHERE c.conrelid = '{table}'::regclass
      AND c.contype = 'f'
      AND a.attname = '{column}';

    EXECUTE format('ALTER TABLE {table} DROP CONSTRAINT %I', fk_name);
    EXECUTE format(
        'ALTER TABLE {table} ADD CONSTRAINT %I '
        'FOREIGN KEY ({column}) REFERENCES {ref_table}({ref_column}) '
        '{on_delete} DEFERRABLE INITIALLY DEFERRED',
        fk_name
    );
END $$;
"""


def _sql(on_delete: str) -> str:
    return "\n".join(
        _LOOKUP_AND_REPLACE.format(
            table=table,
            column=column,
            ref_table=ref_table,
            ref_column=ref_column,
            on_delete=on_delete,
        )
        for table, column, ref_table, ref_column in _FOREIGN_KEYS
    )


_ADD_DB_CASCADE = _sql("ON DELETE CASCADE")
_DROP_DB_CASCADE = _sql("")


